-- ============================================================
-- aqua-8 捕捞预约与规格分仓
-- 关键约束：
--   1) 客户订单按「规格 + 重量区间 + 交付时间」拆分为捕捞预约，同订单同口径自然键唯一；
--   2) 预约锁定后占用库位，其他订单的预约不得占用同一库位；
--   3) 捕捞现场按实际规格分仓：实际均重按当时生效分级规则判级，入对应规格库位；
--   4) 库位状态与待检标识同一事务同步更新，不出现中间态；
--   5) 短装/超装在预约完成时生成差异单，每预约至多一条；
--   6) 临时换车必须登记原因并触发客户通知，客户签收留回执；
--   7) 订单完成时冻结当时生效的分级规则快照，新规则版本不影响已完成订单；
--   8) 补传/补录/重试幂等：request_id 唯一，重复请求返回首次结果，只形成一条可用结果。
-- ============================================================

