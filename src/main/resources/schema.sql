-- ============================================================
-- aqua-14 渔获订单履约
-- 关键约束：
--   1) 履约订单来源于已完成的捕捞订单，按「规格 + 收货点」拆为履约子单，子单可再拆；
--      拆单/再拆/替换收货点一律不改变原订单金额口径（行金额合计恒等于订单总额）；
--   2) 一个捕捞订单至多一个履约订单（uk fishing_order_id），同预约各子单计划净重合计不超实际捕捞量；
--   3) 捕捞后逐箱入冷藏库：记录入库温度、箱号（全局唯一）、毛重/皮重，净重服务端=毛重-皮重，冷库在库重量同事务累加；
--   4) 交接时按当时生效净重差异规则（百分比+绝对容差）逐箱判定，超差箱 FROZEN 冻结在库不出库，正常箱出库扣重；
--   5) 一子单至多一次交接，交接箱集合必须恰好等于该子单全部在库箱；交接单首签有效，重复签收不覆盖首次回执；
--   6) 替换收货点必须审批（审批人+意见缺一不可），通过只改收货点不碰数量金额；
--   7) 拆单结果同步海水养殖管理：发件箱 outbox 保证「外部无响应不假装成功、恢复后按确定性 eventId 重发不重复通知」；
--   8) 客户视图只含签收与差异/数量信息，内部成本/单价/金额/温度/冷库字段一律不下发；
--   9) 所有写操作 requestId 幂等（唯一约束兜底）并写 t_fulfill_change_evidence，同步失败独立事务留证。
-- ============================================================

